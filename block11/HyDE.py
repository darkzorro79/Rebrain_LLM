import os
from openai import OpenAI

# Инициализация клиента (предполагается, что API_KEY в env)
client = OpenAI(
    api_key="API_KEY", # Для локального сервера можно вписать любой текст
    base_url="https://llm.rebrainme.study/" # Либо адрес вашего провайдера/локального хоста
)

def generate_hypothetical_document(query):
    """
    Генерирует фейковый ответ, который выглядит как идеальный документ из базы.
    """
    prompt = f"""
    Напиши короткий отрывок из технической документации, который отвечает на вопрос:
    "{query}"
    Используй профессиональный стиль, технические термины и структуру инструкции.
    Не пиши вступлений, только суть. Длина ответа должна быть не больше 4-х абзацев.
    """

    response = client.chat.completions.create(
        model="gemini-2.5-flash", # Для этой задачи хватит быстрой модели
        messages=[
            {"role": "system", "content": "Ты — технический писатель."},
            {"role": "user", "content": prompt}
        ],
        temperature=0.7
    )

    return response.choices[0].message.content

def get_embedding(text):
    """Получает эмбеддинг текста"""
    response = client.embeddings.create(
        input=text,
        model="gemini-embedding-001"
    )
    return response.data[0].embedding

# --- Эмуляция процесса HyDE ---

user_query = "Почему падает под в кубере?"

# 1. Генерация гипотезы
hypothetical_answer = generate_hypothetical_document(user_query)

print(f"--- USER QUERY ---\n{user_query}\n")
print(f"--- HYPOTHETICAL ANSWER (Generated by LLM) ---\n{hypothetical_answer}\n")

# 2. Векторизация гипотезы (а не вопроса!)
search_vector = get_embedding(hypothetical_answer)

